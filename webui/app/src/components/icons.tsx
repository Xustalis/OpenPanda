/** Inline icon. `size` is in px; defaults to 1em so the surrounding
 *  font-size drives it — the same scaling the emoji had. */
export function Icon({
  name,
  size,
  class: cls,
}: {
  name: IconName
  size?: number
  class?: string
}) {
  return (
    <svg
      width={size ?? '1em'}
      height={size ?? '1em'}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      aria-hidden="true"
      class={`ico${cls ? ' ' + cls : ''}`}
    >
      {paths[name]}
    </svg>
  )
}
