package i18n

// The `panda help` page is the CLI's biggest block of prose (~55 description
// strings), so it lives in its own file rather than inflating messages.go —
// same rules: every key exists in all five locales, {placeholders} match.
// A "\n" inside a description is a hard wrap point: printUsage re-indents
// each segment, so a translation wraps wherever its own word lengths need.

func init() {
	mergeMessages(English, helpEN)
	mergeMessages(ChineseSimp, helpZH)
	mergeMessages(Japanese, helpJA)
	mergeMessages(Spanish, helpES)
	mergeMessages(German, helpDE)
}

func mergeMessages(loc Locale, kv map[string]string) {
	for k, v := range kv {
		messages[loc][k] = v
	}
}

